-- Дело «Позвонить миссионеру» без фразы про молитву по телефону (замечание владельца 10.10: этого не просили).
-- В идущих партиях дело могло быть правлено администратором, поэтому обновление из набора его не трогает:
-- здесь убираются только эти фразы, остальной текст и настройки остаются.
UPDATE "Deed"
SET description = replace(
      replace(description, ', помолиться с ним по телефону', ''),
      ' и за что молились', '')
WHERE title = 'Позвонить миссионеру';
