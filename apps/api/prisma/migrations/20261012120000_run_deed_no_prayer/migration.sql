-- Дело «Пробежка с молитвой» → «Пробежка» без молитвы (решение владельца 12.10: пробежка и молитва плохо совместимы).
-- В идущих партиях дело могло быть правлено администратором, поэтому обновление из набора его не трогает:
-- здесь меняется название и убирается одна фраза, остальной текст и настройки остаются.
UPDATE "Deed"
SET title = 'Пробежка',
    description = regexp_replace(description, '\s*Во время или после пробежки помолиться за команду и за одного человека из церкви\.', '', 'g')
WHERE title IN ('Пробежка с молитвой', 'Утренняя пробежка с молитвой');
