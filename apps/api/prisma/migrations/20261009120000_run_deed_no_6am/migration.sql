-- Дело «Утренняя пробежка с молитвой» → «Пробежка с молитвой» без требования выйти в 6:00 (решение владельца 07.10, повтор 09.10).
-- В идущих партиях дело правил администратор (ценник, процент, текст), поэтому обновление из набора его не тронуло:
-- здесь меняется только название и фраза про 6:00, остальной текст и настройки остаются.
UPDATE "Deed"
SET title = 'Пробежка с молитвой',
    description = regexp_replace(
      regexp_replace(description, 'Выйти на пробежку в 6:00 утра и пробежать', 'Пробежать'),
      '\s*в 6:00 утра\s*', ' ', 'g')
WHERE title = 'Утренняя пробежка с молитвой';
